def axis_tables(rows, base, note):
    """The automatic pipeline line and one table per step varied."""
    parts = [
        "Automatic pipeline: %s.  Each table varies one step, the others held "
        "there%s."
        % (", ".join("%s `%s`" % (k, base[k]) for k in _pipeline.STEPS if k in base), note)
    ]
    axes = []
    for r in rows:
        if r["axis"] not in axes:
            axes.append(r["axis"])
    for axis in axes:
        arows = [r for r in rows if r["axis"] == axis]
        table = (
            "| %s | frames/s | compressed GB/s | pixels GB/s | vs auto |\n"
            "|---|---:|---:|---:|---|\n" % axis
        )
        for r in sorted([r for r in arows if "fps" in r], key=lambda r: -r["fps"]):
            is_auto = all(r["pipeline"].get(k) == base[k] for k in base)
            table += "| %s | %.1f | %.3f | %.2f | %s |\n" % (
                ("**`%s`**" if is_auto else "`%s`") % r["pipeline"].get(axis),
                r["fps"],
                r["compressed_gbs"],
                r["pixel_gbs"],
                ("**auto**; " if is_auto else "") + kernel_check(r),
            )
        for r in arows:
            if "refused" in r:
                table += "| `%s` | refused: %s | | | |\n" % (
                    r["pipeline"].get(axis),
                    r["refused"].replace("|", "\\|"),
                )
        parts.append(table)
    return parts


