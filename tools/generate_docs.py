PUBLIC_CLASSES = ("chunk2sparse", "chunk2sparseCSC")
PUBLIC_METHODS = ("__call__", "multi", "from_buffer", "from_frames", "coo")


def signature(obj, name):
    """name(params) as written in the source: a function or class default is shown by its name,
    not by its repr (which holds a memory address)."""
    try:
        text = "%s%s" % (name, inspect.signature(obj))
    except (TypeError, ValueError):
        return name
    text = re.sub(r"<function (\w+) at 0x[0-9a-f]+>", r"\1", text)
    return re.sub(r"<class '([\w.]+)'>", r"\1", text)


def docblock(obj):
    doc = inspect.getdoc(obj)
    if not doc:
        raise SystemExit(
            "%r has no docstring: write one in the code, not here"
            % getattr(obj, "__qualname__", obj)
        )
    return fence("text", doc)


def api_page():
    parts = [
        "# API reference\n",
        "Everything here is read from the installed module: the signatures by "
        "introspection, the text from the docstrings in `src/`.\n",
        "## The package\n",
        fence("text", inspect.getdoc(b)),
    ]
    for name in PUBLIC_CLASSES:
        cls = getattr(b, name)
        parts.append("## %s\n" % name)
        parts.append(fence("python", "class " + signature(cls, name)))
        parts.append(docblock(cls))
        for m in PUBLIC_METHODS:
            meth = getattr(cls, m)
            parts.append("### %s.%s\n" % (name, m))
            parts.append(fence("python", signature(meth, m)))
            parts.append(docblock(meth))
    funcs = [n for n in b.__all__ if n not in PUBLIC_CLASSES and callable(getattr(b, n))]
    for name in funcs:
        fn = getattr(b, name)
        parts.append("## %s\n" % name)
        parts.append(fence("python", signature(fn, name)))
        parts.append(docblock(fn))
    consts = [n for n in b.__all__ if not callable(getattr(b, n))]
    parts.append("## Constants\n")
    parts.append(
        "| name | value |\n|---|---|\n"
        + "".join("| `%s` | `%r` |\n" % (n, getattr(b, n)) for n in consts)
    )
    parts.append(
        "\n## Decode errors\n\nA negative return from the native decode is "
        "raised as an `Exception` with this text (`_DECODE_ERRORS` in "
        "`src/__init__.py`):\n\n| code | meaning |\n|---|---|\n"
        + "".join(
            "| %d | %s |\n" % (k, v) for k, v in sorted(b._DECODE_ERRORS.items(), reverse=True)
        )
    )
    parts.append("\n" + provenance())
    return "\n".join(parts)


