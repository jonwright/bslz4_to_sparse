def _ast_signature(fn):
    args = ast.unparse(fn.args)
    if args.startswith("self, "):
        args = args[len("self, ") :]
    elif args == "self":
        args = ""
    return "%s(%s)" % (fn.name, args)


def gpu_page():
    """src/cuda/ read as source (ast): importing it needs cupy and a GPU, the docs build has neither."""

    def tree(name):
        with open(os.path.join(REPO, "src", "cuda", name)) as fh:
            return ast.parse(fh.read())

    def need(node, what):
        doc = ast.get_docstring(node)
        if not doc:
            raise SystemExit(
                "src/cuda: %s has no docstring: write one in the code, not here" % what
            )
        return fence("text", doc)

    init, gpu = tree("__init__.py"), tree("_gpu.py")
    parts = [
        "# GPU decoder\n",
        "Optional: `bslz4_to_sparse.cuda` needs cupy and a CUDA GPU, and Python 3.  The text "
        "below is read from the docstrings in `src/cuda/`.\n",
        "## The package\n",
        need(init, "the package"),
        "## How it differs from the CPU classes\n",
        need(gpu, "_gpu.py"),
    ]
    classes = {n.name: n for n in gpu.body if isinstance(n, ast.ClassDef)}
    for cname in ("chunk2sparse", "chunk2sparseCSC"):
        cls = classes[cname]
        methods = {n.name: n for n in cls.body if isinstance(n, ast.FunctionDef)}
        parts += [
            "## cuda.%s\n" % cname,
            fence(
                "python", "class " + _ast_signature(methods["__init__"]).replace("__init__", cname)
            ),
            need(cls, cname),
        ]
        for m in ("set_top_pixels", "multi", "from_buffer", "__call__", "coo"):
            fn = (
                methods.get(m)
                or classes["chunk2sparse"].body
                and next(
                    n
                    for n in classes["chunk2sparse"].body
                    if isinstance(n, ast.FunctionDef) and n.name == m
                )
            )
            parts += [
                "### %s.%s\n" % (cname, m),
                fence("python", _ast_signature(fn)),
                need(fn, "%s.%s" % (cname, m)),
            ]
    for n in gpu.body:
        if isinstance(n, ast.FunctionDef) and n.name == "release_shared":
            parts += ["## release_shared\n", fence("python", _ast_signature(n)), need(n, n.name)]
    parts.append("\n" + provenance())
    return "\n".join(parts)


def conveyor_page():
    from bslz4_to_sparse import conveyor as cv

    def section(name, kind):
        obj = getattr(cv, name)
        out = ["## %s\n" % name]
        if inspect.isclass(obj):
            out.append(fence("python", "class " + signature(obj, name)))
        else:
            out.append(fence("python", signature(obj, name)))
        out.append(docblock(obj))
        if inspect.isclass(obj):
            for m, f in vars(obj).items():
                if m.startswith("_"):
                    continue
                if isinstance(f, (classmethod, staticmethod)):  # as the user calls it
                    f = getattr(obj, m)
                elif isinstance(f, property):
                    out += ["### %s.%s (property)\n" % (name, m), docblock(f)]
                    continue
                if callable(f):
                    out += [
                        "### %s.%s\n" % (name, m),
                        fence("python", signature(f, m)),
                        docblock(f),
                    ]
        return out

    parts = [
        "# Conveyor\n",
        "The conveyor feeds many files to decoders on one machine, in pure Python.  It is "
        "not the pipeline (the steps inside a decoder).  Read from the docstrings in "
        "`src/conveyor/`.\n",
        "## The package\n",
        fence("text", inspect.getdoc(cv)),
    ]
    groups = (
        (
            "Chunk indexes and units",
            (
                "make_work_units",
                "WorkUnit",
                "Index",
                "read_index",
                "write_index",
                "harvest",
                "sidecar_path",
                "StaleIndex",
            ),
        ),
        ("Running", ("run", "iterate", "report", "numa_nodes")),
        ("Decoders", ("CpuBackend", "DecompressBackend", "GpuBackend")),
        (
            "Sinks",
            (
                "Sink",
                "NullSink",
                "TeeSink",
                "check_powder_size",
                "ImageD11SparseSink",
                "imaged11_name",
                "RingSink",
                "rings_name",
                "peak_windows",
            ),
        ),
        (
            "Integrator state",
            ("Integrator", "IntegratorStack", "fixed_weights", "clip_exact_powder"),
        ),
    )
    layouts = {  # the module docstrings that hold the file layouts the class docstrings point to
        "Sinks": ("_sinks", "_sparsefile", "_ringfile"),
        "Integrator state": ("_integrator",),
    }
    for title, names in groups:
        parts.append("# %s\n" % title)
        for mod in layouts.get(title, ()):
            m = importlib.import_module("bslz4_to_sparse.conveyor." + mod)
            parts += [
                "## Layout and rules: `%s`\n" % mod.lstrip("_"),
                fence("text", inspect.getdoc(m)),
            ]
        for name in names:
            parts += section(name, title)
    placed = set(n for _, names in groups for n in names)
    missing = [n for n in cv.__all__ if n not in placed]
    if missing:
        raise SystemExit("conveyor names with no place on the page: %r" % (missing,))
    parts.append("\n" + provenance())
    return "\n".join(parts)


