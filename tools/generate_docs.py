#!/usr/bin/env python3
"""Generate the documentation pages from the code, by running it.

Every page under docs/gen/ is written here and nowhere else (docs/gen/ is
git-ignored; see docs/AGENTS.md):

  docs/gen/examples/<name>.md  each examples/ex*.py: its docstring, its source,
                               and the output of running it now
  docs/gen/api.md              the docstrings and signatures of the public API,
                               and the decode error codes, read from the module
  docs/gen/pipelines.md        every pipeline step value and what it needs,
                               from src/_pipeline.py
  docs/gen/acknowledgements.md the Acknowledgements and References of
                               README.md, and the licences in licenses/
  docs/gen/kernels.md          docs/bench/kernels_*.json: every pipeline on one
                               data set (tools/bench_kernels.py, never here)
  docs/gen/performance.md      docs/bench/real_data_*.json, one per machine
                               (measured there by tools/bench_docs.py, never here)

An example that raises or exits non-zero stops the build: the site cannot
show an example that does not run.  The bslz4_to_sparse that is imported
(the installed wheel in CI, or BSLZ4_TO_SPARSE_PATH) is the one documented.

    BSLZ4_TO_SPARSE_PATH=lib python3 tools/generate_docs.py
    mkdocs build --strict -f docs/mkdocs.yml
"""
