def write(rel, text):
    path = os.path.join(GEN, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write(text)
    print("wrote", os.path.relpath(path, REPO))


def fence(lang, body):
    return "```%s\n%s\n```\n" % (lang, body.rstrip("\n"))


# ---------------------------------------------------------------- examples

def run_example(path):
    """stdout of running the example as a user would, in an empty directory."""
    env = dict(os.environ)
    pkg_parent = os.path.dirname(os.path.dirname(os.path.abspath(b.__file__)))
    env["PYTHONPATH"] = os.pathsep.join([pkg_parent] + [p for p in [env.get("PYTHONPATH")] if p])
    r = subprocess.run([sys.executable, path], env=env, cwd=os.path.dirname(path),
                       stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if r.returncode != 0:
        raise SystemExit("example %s failed (exit %d):\n%s%s"
                         % (os.path.relpath(path, REPO), r.returncode,
                            r.stdout.decode(), r.stderr.decode()))
    return r.stdout.decode()


def split_docstring(source):
    """(title, body, code) of an example: its module docstring and the rest."""
    mod = compile(source, "<example>", "exec", 0x400)          # PyCF_ONLY_AST
    doc = inspect.cleandoc(mod.body[0].value.value)
    title, _, body = doc.partition("\n")
    end = mod.body[1].lineno - 1 if len(mod.body) > 1 else len(source.splitlines())
    code = "\n".join(source.splitlines()[end:]).strip("\n")
    return title.strip().rstrip("."), body.strip(), code


def example_page(path):
    with open(path) as fh:
        source = fh.read()
    title, body, code = split_docstring(source)
    out = run_example(path)
    rel = os.path.relpath(path, REPO)
    return title, (
        "# %s\n\n%s\n\n" % (title, body)
        + "Source: [`%s`](%s/blob/main/%s), run as `python %s`.\n\n" % (rel, GITHUB, rel, rel)
        + fence("python", code)
        + "\nOutput, from running it when this page was built:\n\n"
        + fence("text", out)
        + "\n" + provenance())


# ---------------------------------------------------------------- API

PUBLIC_CLASSES = ("chunk2sparse", "chunk2sparseCSC")
PUBLIC_METHODS = ("__call__", "multi", "decode_offsets", "coo")


def signature(obj, name):
    try:
        return "%s%s" % (name, inspect.signature(obj))
    except (TypeError, ValueError):
        return name


def docblock(obj):
    doc = inspect.getdoc(obj)
    if not doc:
        raise SystemExit("%r has no docstring: write one in the code, not here"
                         % getattr(obj, "__qualname__", obj))
    return fence("text", doc)


def api_page():
    parts = ["# API reference\n",
             "Everything here is read from the installed module: the signatures by "
             "introspection, the text from the docstrings in `src/`.\n",
             "## The package\n", fence("text", inspect.getdoc(b))]
    for name in PUBLIC_CLASSES:
        cls = getattr(b, name)
        parts.append("## %s\n" % name)
        parts.append(fence("python", "class " + signature(cls, name)))
        parts.append(docblock(cls))
        for m in PUBLIC_METHODS:
            meth = getattr(cls, m)
            parts.append("### %s.%s\n" % (name, m))
            parts.append(fence("python", signature(meth, m)))
            parts.append(docblock(meth))
    funcs = [n for n in b.__all__ if n not in PUBLIC_CLASSES and callable(getattr(b, n))]
    for name in funcs:
        fn = getattr(b, name)
        parts.append("## %s\n" % name)
        parts.append(fence("python", signature(fn, name)))
        parts.append(docblock(fn))
    consts = [n for n in b.__all__ if not callable(getattr(b, n))]
    parts.append("## Constants\n")
    parts.append("| name | value |\n|---|---|\n"
                 + "".join("| `%s` | `%r` |\n" % (n, getattr(b, n)) for n in consts))
    parts.append("\n## Decode errors\n\nA negative return from the native decode is "
                 "raised as an `Exception` with this text (`_DECODE_ERRORS` in "
                 "`src/__init__.py`):\n\n| code | meaning |\n|---|---|\n"
                 + "".join("| %d | %s |\n" % (k, v) for k, v in sorted(b._DECODE_ERRORS.items(),
                                                                        reverse=True)))
    parts.append("\n" + provenance())
    return "\n".join(parts)


